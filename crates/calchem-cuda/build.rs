use std::env;
use std::path::PathBuf;
use std::process::Command;

fn main() {
    println!("cargo:rustc-check-cfg=cfg(no_cuda)");
    println!("cargo:rerun-if-changed=src/cuda_kernels.cu");

    let nvcc_check = Command::new("nvcc").arg("--version").output();
    let has_nvcc = match nvcc_check {
        Ok(out) => out.status.success(),
        Err(_) => false,
    };

    if !has_nvcc {
        println!(
            "cargo:warning=NVCC not found; calchem-cuda will compile with CPU fallback stubs."
        );
        println!("cargo:rustc-cfg=no_cuda");
        return;
    }

    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let cu_path = manifest_dir.join("src").join("cuda_kernels.cu");
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let cubin_path = out_dir.join("calchem_kernels_sm120.cubin");
    let cubin_header_path = out_dir.join("calchem_cubin.h");
    let lib_name = if cfg!(target_os = "windows") {
        "calchem_cuda.lib"
    } else {
        "libcalchem_cuda.a"
    };
    let lib_path = out_dir.join(lib_name);

    let mut compiled = false;
    let ccbin = "D:\\MICROS~3\\VC\\Tools\\MSVC\\14.51.36231\\bin\\Hostx64\\x64";

    // Step 1: Compile device kernel to native sm_120 cubin via NVCC
    let cubin_cmd = format!(
        "& nvcc -ccbin {ccbin} -arch=sm_120 --cubin -O3 -Xcompiler /MD -Xcompiler /wd4819 '{}' -o '{}'",
        cu_path.display(),
        cubin_path.display()
    );
    let cubin_ok = Command::new("powershell")
        .arg("-NoProfile")
        .arg("-Command")
        .arg(&cubin_cmd)
        .status()
        .map(|s| s.success() && cubin_path.exists())
        .unwrap_or(false);

    if cubin_ok {
        if let Ok(bytes) = std::fs::read(&cubin_path) {
            let mut header = String::from("// Auto-generated by build.rs from NVCC sm_120 cubin\n");
            header.push_str("static const unsigned char CALCHEM_SM120_CUBIN[] = {");
            for (i, b) in bytes.iter().enumerate() {
                if i % 16 == 0 {
                    header.push_str("\n    ");
                }
                header.push_str(&format!("0x{:02x}, ", b));
            }
            header.push_str("\n};\n");
            let _ = std::fs::write(&cubin_header_path, header);
        }

        // Step 2: Compile host + device library via NVCC with embedded cubin header
        let ps_cmd = format!(
            "& nvcc -ccbin {ccbin} -arch=sm_120 --lib -O3 -DHAVE_CALCHEM_CUBIN_H -I'{}' -Xcompiler /MD -Xcompiler /wd4819 '{}' -o '{}'",
            out_dir.display(),
            cu_path.display(),
            lib_path.display()
        );
        if let Ok(s) = Command::new("powershell")
            .arg("-NoProfile")
            .arg("-Command")
            .arg(&ps_cmd)
            .status()
        {
            if s.success() && lib_path.exists() {
                compiled = true;
            }
        }
    }

    // Never substitute an unverified prebuilt archive after a source build failure:
    // it can silently reintroduce old kernels and invalidate every source-level fix.

    if compiled {
        println!("cargo:rustc-link-search=native={}", out_dir.display());
        println!("cargo:rustc-link-lib=static=calchem_cuda");

        if let Ok(cuda_path) = env::var("CUDA_PATH") {
            let p = PathBuf::from(cuda_path).join("lib").join("x64");
            println!("cargo:rustc-link-search=native={}", p.display());
        } else {
            println!("cargo:rustc-link-search=native=D:\\NVIDIA_CUDA_Toolkit\\lib\\x64");
            println!("cargo:rustc-link-search=native=C:\\Program Files\\NVIDIA GPU Computing Toolkit\\CUDA\\v13.3\\lib\\x64");
        }
        println!("cargo:rustc-link-lib=static=cudart_static");
    } else {
        println!("cargo:warning=CUDA kernels could not be built; using CPU fallback");
        println!("cargo:rustc-cfg=no_cuda");
    }
}
