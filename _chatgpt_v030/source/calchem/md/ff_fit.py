from __future__ import annotations

from typing import Optional, Dict, Any

import numpy as np

from ..utils.logging_utils import get_logger

logger = get_logger(__name__)


class ForceFieldFit:
    def __init__(self, method):
        self.method = method
        self.parameters: Dict[str, Any] = {}

    def fit_charges(self, method: str = "resp") -> np.ndarray:
        logger.warning(f"Force field charge fitting ({method}) not fully implemented")
        return np.array([])

    def fit_bonds(self) -> dict:
        logger.warning("Force field bond fitting not fully implemented")
        return {}

    def fit_angles(self) -> dict:
        logger.warning("Force field angle fitting not fully implemented")
        return {}

    def fit_dihedrals(self) -> dict:
        logger.warning("Force field dihedral fitting not fully implemented")
        return {}

    def write_itp(self, filename: str) -> None:
        with open(filename, "w") as f:
            f.write("; GROMACS ITP file generated by CalChem\n")
            f.write("[ moleculetype ]\n")
            f.write("MOL  3\n\n")
            f.write("[ atoms ]\n")
            f.write(";   nr  type  resi  res   atom  cgnr  charge      mass\n")
            f.write("[ bonds ]\n")
            f.write("[ angles ]\n")
            f.write("[ dihedrals ]\n")

        logger.info(f"ITP file written: {filename}")

    def __repr__(self) -> str:
        return f"ForceFieldFit(method={self.method})"
