def integrate_angular(f):
    """数值积分角向函数。"""
    n_theta = 100
    n_phi = 200
    dtheta = math.pi / n_theta
    dphi = 2 * math.pi / n_phi
    result = 0.0
    for i in range(n_theta):
        theta = (i + 0.5) * dtheta
        sin_theta = math.sin(theta)
        for j in range(n_phi):
            phi = (j + 0.5) * dphi
            result += f(theta, phi) * sin_theta * dtheta * dphi
    return result

