def boys(n, x):
    if x < 1e-10:
        return 1.0 / (2*n + 1)
    result = 0.0
    for k in range(100):
        term = (x**k) / math.factorial(k) / (2*n + 2*k + 1)
        result += term
        if abs(term) < 1e-15:
            break
    return result * math.exp(-x)


def coulomb_radial(f, g, R_max=50):
    """球对称库仑积分的数值计算。"""
    def inner(r1):
        part1, _ = quad(lambda r2: r2**2 * g(r2) / r1, 0, r1)
        part2, _ = quad(lambda r2: r2**2 * g(r2) / r2, r1, R_max)
        return part1 + part2
    
    def integrand(r1):
        return 16 * math.pi**2 * r1**2 * f(r1) * inner(r1)
    
    result, _ = quad(integrand, 0, R_max)
    return result


