def radial_integral(l, beta):
    """计算 R_l = ∫_0^∞ ∫_0^∞ r1^4 r2^4 exp(-βr1²-βr2²) (r_<^l / r_>^{l+1}) dr1 dr2"""
    # 拆分 r1 < r2 和 r1 > r2
    # 区域 1: r1 < r2, r_< = r1, r_> = r2 → r_<^l / r_>^{l+1} = r1^l / r2^{l+1}
    # 区域 2: r1 > r2, r_< = r2, r_> = r1 → r_<^l / r_>^{l+1} = r2^l / r1^{l+1}
    # 
    # 两个区域对称，所以 R_l = 2 * ∫_0^∞ ∫_{r1}^∞ r1^4 r2^4 exp(-βr1²-βr2²) * r1^l / r2^{l+1} dr2 dr1
    # = 2 * ∫_0^∞ r1^(4+l) exp(-βr1²) [∫_{r1}^∞ r2^(4-(l+1)) exp(-βr2²) dr2] dr1
    # = 2 * ∫_0^∞ r1^(4+l) exp(-βr1²) [∫_{r1}^∞ r2^(3-l) exp(-βr2²) dr2] dr1
    
    def inner(r1):
        result, _ = quad(lambda r2: r2**(3-l) * math.exp(-beta * r2**2), r1, 10)
        return result
    
    def integrand(r1):
        return 2 * r1**(4+l) * math.exp(-beta * r1**2) * inner(r1)
    
    result, _ = quad(integrand, 0, 10)
    return result

