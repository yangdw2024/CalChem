from __future__ import annotations

from typing import Optional

import numpy as np

from ..mol.molecule import Molecule
from ..utils.logging_utils import get_logger

logger = get_logger(__name__)


class GromacsIO:
    def __init__(self):
        pass

    def read_gro(self, filename: str) -> Molecule:
        from ..io.input import read_gro

        return read_gro(filename)

    def write_gro(self, mol: Molecule, filename: str, title: str = "CalChem") -> None:
        coords_nm = mol.coordinates / 10.0

        with open(filename, "w") as f:
            f.write(f"{title}\n")
            f.write(f"{mol.natom:5d}\n")

            for i, (sym, coord) in enumerate(zip(mol.symbols, coords_nm)):
                res_num = (i // 10) + 1
                res_name = "MOL"
                atom_name = f"{sym}{i + 1}"
                atom_num = i + 1

                f.write(
                    f"{res_num:5d}{res_name:<5s}{atom_name:>5s}{atom_num:5d}"
                    f"{coord[0]:8.3f}{coord[1]:8.3f}{coord[2]:8.3f}\n"
                )

            f.write("  10.0  10.0  10.0\n")

        logger.info(f"GROMACS file written: {filename}")

    def write_top(self, mol: Molecule, filename: str, itp_file: str = "mol.itp") -> None:
        with open(filename, "w") as f:
            f.write("; GROMACS topology file generated by CalChem\n\n")
            f.write(f'#include "{itp_file}"\n\n')
            f.write("[ system ]\nCalChem system\n\n")
            f.write("[ molecules ]\n")
            f.write(f"MOL  1\n")

        logger.info(f"GROMACS topology written: {filename}")

    def __repr__(self) -> str:
        return "GromacsIO()"
