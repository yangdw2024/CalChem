//! 内置基组原始数据库。
//!
//! 数据来源：标准 MolSSI Basis Set Exchange（与 Python 参照 calchem/basis/basis_data.py 一致）。
//! 本文件目前种子化了 STO-3G（H, He, C, N, O, F, Ne），其余基组在后续扩展中补齐。
//!
//! 约定：收缩系数是“归一化原语”的系数，原语归一化在积分代码中施加。

use super::RawShell;

/// 便捷构造一个原始壳层。
fn sh(l: u8, exps: &[f64], coefs: &[f64]) -> RawShell {
    RawShell {
        angular_l: l,
        exponents: exps.to_vec(),
        coefficients: coefs.to_vec(),
    }
}

/// 返回指定基组、指定元素（原子序数）的原始壳层；无数据返回 None。
pub fn element_records(basis: &str, z: u8) -> Option<Vec<RawShell>> {
    match basis {
        "sto-3g" => Some(sto3g(z)?),
        _ => None,
    }
}

/// STO-3G（最小基组，每壳层 3 个原语）。
fn sto3g(z: u8) -> Option<Vec<RawShell>> {
    // 通用 s 收缩系数（H/He 与重原子内层 s 相同）。
    const S_CORE: [f64; 3] = [0.15432897, 0.53532814, 0.44463454];
    // 重原子价层 s 系数。
    const S_VAL: [f64; 3] = [-0.09996723, 0.39951283, 0.70011547];
    // 价层 p 系数。
    const P_VAL: [f64; 3] = [0.15591627, 0.60768372, 0.39195739];

    let recs = match z {
        1 => vec![sh(0, &[3.42525091, 0.62391373, 0.16885540], &S_CORE)],
        2 => vec![sh(0, &[6.36242139, 1.15892300, 0.31364979], &S_CORE)],
        6 => vec![
            sh(0, &[71.61683735, 13.04509632, 3.53051216], &S_CORE),
            sh(0, &[2.94124940, 0.68348310, 0.22228990], &S_VAL),
            sh(1, &[2.94124940, 0.68348310, 0.22228990], &P_VAL),
        ],
        7 => vec![
            sh(0, &[99.10616902, 18.05231239, 4.88566023], &S_CORE),
            sh(0, &[3.78045588, 0.87849662, 0.28571438], &S_VAL),
            sh(1, &[3.78045588, 0.87849662, 0.28571438], &P_VAL),
        ],
        8 => vec![
            sh(0, &[130.70932140, 23.80886605, 6.44360831], &S_CORE),
            sh(0, &[5.03315132, 1.16959610, 0.38038900], &S_VAL),
            sh(1, &[5.03315132, 1.16959610, 0.38038900], &P_VAL),
        ],
        9 => vec![
            sh(0, &[166.67913400, 30.36081233, 8.21682067], &S_CORE),
            sh(0, &[6.46480325, 1.50228124, 0.48858849], &S_VAL),
            sh(1, &[6.46480325, 1.50228124, 0.48858849], &P_VAL),
        ],
        10 => vec![
            sh(0, &[207.01662330, 37.70815124, 10.20529770], &S_CORE),
            sh(0, &[8.24631512, 1.91626629, 0.62322926], &S_VAL),
            sh(1, &[8.24631512, 1.91626629, 0.62322926], &P_VAL),
        ],
        _ => return None,
    };
    Some(recs)
}
