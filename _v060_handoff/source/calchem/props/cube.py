from __future__ import annotations

from typing import Optional, Tuple

import numpy as np

from ..mol.molecule import Molecule
from ..utils.logging_utils import get_logger

logger = get_logger(__name__)


class CubeFile:
    def __init__(
        self,
        mol: Molecule,
        origin: Optional[np.ndarray] = None,
        spacing: Tuple[float, float, float] = (0.2, 0.2, 0.2),
        n_points: Tuple[int, int, int] = (80, 80, 80),
    ):
        self.mol = mol
        self.spacing = np.array(spacing)
        self.n_points = np.array(n_points)

        if origin is None:
            coords = mol.coordinates
            self.origin = coords.min(axis=0) - 3.0
        else:
            self.origin = np.array(origin)

        self.data: Optional[np.ndarray] = None

    def generate(self, method, mo_index: int = 0) -> np.ndarray:
        logger.warning("Cube file generation not fully implemented")
        self.data = np.zeros(tuple(self.n_points))
        return self.data

    def save(self, filename: str, title: str = "") -> None:
        if self.data is None:
            raise RuntimeError("No data to save. Call generate() first.")

        with open(filename, "w") as f:
            f.write(f"Generated by CalChem\n{title}\n")
            f.write(f"{self.mol.natom:5d}  ")
            f.write(f"{self.origin[0]:12.6f}{self.origin[1]:12.6f}{self.origin[2]:12.6f}\n")

            for i in range(3):
                f.write(f"{self.n_points[i]:5d}  ")
                vec = np.zeros(3)
                vec[i] = self.spacing[i]
                f.write(f"{vec[0]:12.6f}{vec[1]:12.6f}{vec[2]:12.6f}\n")

            for i, (sym, coord) in enumerate(zip(self.mol.symbols, self.mol.coordinates)):
                from ..utils.constants import ATOMIC_NUMBERS

                atomic_num = ATOMIC_NUMBERS.get(sym, 0)
                f.write(
                    f"{atomic_num:5d}  0.000000  "
                    f"{coord[0]:12.6f}{coord[1]:12.6f}{coord[2]:12.6f}\n"
                )

            data_flat = self.data.flatten()
            for i in range(0, len(data_flat), 6):
                vals = data_flat[i : i + 6]
                f.write(" " + " ".join(f"{v:13.5e}" for v in vals) + "\n")

    @classmethod
    def load(cls, filename: str) -> "CubeFile":
        with open(filename, "r") as f:
            lines = f.readlines()

        idx = 2
        parts = lines[idx].split()
        natom = int(parts[0])
        origin = np.array([float(parts[1]), float(parts[2]), float(parts[3])])

        n_points = np.zeros(3, dtype=int)
        spacing = np.zeros(3)
        for i in range(3):
            idx += 1
            parts = lines[idx].split()
            n_points[i] = int(parts[0])
            spacing[i] = float(parts[i + 1])

        symbols = []
        coordinates = []
        for i in range(natom):
            idx += 1
            parts = lines[idx].split()
            from ..utils.constants import ELEMENTS

            atomic_num = int(parts[0])
            sym = ELEMENTS.get(atomic_num, "X")
            symbols.append(sym)
            coordinates.append([float(parts[2]), float(parts[3]), float(parts[4])])

        mol = Molecule(symbols, coordinates)

        idx += 1
        data_values = []
        for line in lines[idx:]:
            data_values.extend([float(x) for x in line.split()])

        data = np.array(data_values).reshape(tuple(n_points))

        cube = cls(mol, origin=origin, spacing=tuple(spacing), n_points=tuple(n_points))
        cube.data = data

        return cube

    def __repr__(self) -> str:
        return f"CubeFile(mol={self.mol}, n_points={self.n_points})"
